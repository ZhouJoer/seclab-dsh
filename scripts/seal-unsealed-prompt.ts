/** Seal the security workbench direct-execution contract into its generated slot module.
 * Run after editing packages/experimental/security-analysis/resources/prompts/unsealed.md:
 * `pnpm tsx scripts/seal-unsealed-prompt.ts`
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  openUnsealedPrompt,
  sealUnsealedPrompt,
  type SealedSlot,
} from '../packages/experimental/security-analysis/src/unsealed-prompt.ts'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const pkg = path.join(root, 'packages/experimental/security-analysis')
const source = path.join(pkg, 'resources', 'prompts', 'unsealed.md')
const dest = path.join(pkg, 'src', 'unsealed-prompt-slot.ts')

const text = await readFile(source, 'utf8')
if (!text.trim()) throw new Error(`Empty contract source: ${source}`)
if (!text.includes('AUTHORIZED SCOPE')) throw new Error('Contract source lost its AUTHORIZED SCOPE section')

const slot: SealedSlot = sealUnsealedPrompt(text)
if (openUnsealedPrompt(slot) !== text) throw new Error('Sealed slot failed its round-trip verification')

const rows = (value: string, width = 96): string[] =>
  Array.from({ length: Math.ceil(value.length / width) }, (_, index) => value.slice(index * width, (index + 1) * width))

// Base64 fields never contain quotes or backslashes; single-quoted literals match repository lint.
const literal = (values: readonly string[]) => `[${values.map(value => `'${value}'`).join(', ')}]`

const module = `/** Generated by scripts/seal-unsealed-prompt.ts from resources/prompts/unsealed.md; regenerate instead of editing. @module */
/** Base64-encoded sealed prompt bytes. */
export const SLOT = ${literal(rows(slot.SLOT))}.join('')
/** Base64-encoded mask used to recover the prompt encryption key. */
export const MASK = '${slot.MASK}'
/** Base64-encoded authentication tag for the sealed prompt. */
export const TAG = '${slot.TAG}'
/** Base64-encoded initialization vector for the sealed prompt. */
export const IV = '${slot.IV}'
`

await mkdir(path.dirname(dest), { recursive: true })
await writeFile(dest, module, 'utf8')
console.log(`sealed ${text.length} chars -> ${path.relative(root, dest)}`)
